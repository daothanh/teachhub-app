// Sinh `lib/src/api/api_error_code.g.dart` từ `contracts/error_codes.json` của
// teachhub-backend (nguồn duy nhất cho API, web, app — spec §5.6).
//
//   dart run tool/gen_error_codes.dart [đường dẫn error_codes.json]
//   dart run tool/gen_error_codes.dart --check   # CI: đỏ nếu bản sinh lệch hợp đồng
//
// Mặc định đọc repo backend nằm cạnh repo app (…/TeachHub/teachhub-backend).
// Bản sao hợp đồng được ghi vào `contracts/error_codes.json` để test đối chiếu.
import 'dart:convert';
import 'dart:io';

const _out = 'lib/src/api/api_error_code.g.dart';
const _snapshot = 'contracts/error_codes.json';

void main(List<String> args) {
  final check = args.contains('--check');
  final source =
      args.where((a) => !a.startsWith('--')).firstOrNull ??
      '../../../teachhub-backend/contracts/error_codes.json';
  final raw = File(source).readAsStringSync();
  final codes = (jsonDecode(raw) as Map<String, dynamic>).map(
    (k, v) => MapEntry(k, (v as Map<String, dynamic>)['http'] as int),
  );

  final buf = StringBuffer()
    ..writeln('// GENERATED by tool/gen_error_codes.dart — không sửa tay.')
    ..writeln('// Nguồn: teachhub-backend/contracts/error_codes.json')
    ..writeln()
    ..writeln("part of 'api_error_code.dart';")
    ..writeln()
    ..writeln('/// Mã lỗi `code` của TeachHub API kèm HTTP status (spec §5.6).')
    ..writeln('enum ApiErrorCode {');
  for (final MapEntry(key: code, value: http) in codes.entries) {
    buf.writeln("  ${_camel(code)}('$code', $http),");
  }
  buf
    ..writeln()
    ..writeln('  /// Mã server mới hơn bản app này (app cũ chưa sinh lại).')
    ..writeln("  unknown('', 0);")
    ..writeln()
    ..writeln('  const ApiErrorCode(this.wire, this.http);')
    ..writeln()
    ..writeln('  /// Giá trị `code` trong body lỗi.')
    ..writeln('  final String wire;')
    ..writeln()
    ..writeln('  /// HTTP status mà API trả kèm mã này; `0` với [unknown].')
    ..writeln('  final int http;')
    ..writeln()
    ..writeln('  static ApiErrorCode fromWire(String? code) =>')
    ..writeln('      _byWire[code] ?? ApiErrorCode.unknown;')
    ..writeln('}')
    ..writeln()
    ..writeln(
      'final _byWire = {for (final c in ApiErrorCode.values) c.wire: c};',
    );

  final generated = _format(buf.toString());
  if (check) {
    final same =
        File(_out).existsSync() &&
        File(_out).readAsStringSync() == generated &&
        File(_snapshot).existsSync() &&
        File(_snapshot).readAsStringSync() == raw;
    if (!same) {
      stderr.writeln(
        '$_out lệch contracts/error_codes.json — chạy dart run tool/gen_error_codes.dart',
      );
      exit(1);
    }
    return;
  }
  File(_out).writeAsStringSync(generated);
  File(_snapshot).writeAsStringSync(raw);
  stdout.writeln('Đã sinh ${codes.length} mã lỗi → $_out');
}

/// Định dạng như `dart format` để file sinh ra không đổi khi format cả repo.
String _format(String source) {
  final tmp = Directory.systemTemp.createTempSync('gen_error_codes');
  try {
    final file = File('${tmp.path}/out.dart')..writeAsStringSync(source);
    final r = Process.runSync('dart', ['format', file.path]);
    if (r.exitCode != 0) throw StateError('dart format lỗi: ${r.stderr}');
    return file.readAsStringSync();
  } finally {
    tmp.deleteSync(recursive: true);
  }
}

String _camel(String upperSnake) {
  final parts = upperSnake.toLowerCase().split('_');
  return parts.first +
      parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1)).join();
}
